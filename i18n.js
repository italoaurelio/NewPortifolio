const LANGS = ["pt", "en", "es"];
const HTML_LANG = { pt: "pt-BR", en: "en", es: "es" };

function detectLang() {
    let saved = null;
    try { saved = localStorage.getItem("lang"); } catch (e) { /* modo privado, segue o baile */ }
    if (LANGS.includes(saved)) return saved;
    const nav = (navigator.language || "").toLowerCase();
    if (nav.startsWith("pt")) return "pt";
    if (nav.startsWith("es")) return "es";
    return "en";
}

const i18n = {
    lang: detectLang(),
    langs: LANGS,

    t(key) {
        return I18N[this.lang]?.[key] ?? I18N.en[key] ?? key;
    },

    // Campo de JSON pode ser string OU {pt, en, es}: resolve com fallback 🤝
    field(v) {
        if (v == null) return "";
        if (typeof v === "string" || Array.isArray(v)) return v;
        return v[this.lang] ?? v.en ?? v.pt ?? "";
    },

    setLang(lang) {
        if (!LANGS.includes(lang)) lang = "en";
        this.lang = lang;
        try { localStorage.setItem("lang", lang); } catch (e) { /* sem storage, sem drama */ }
        document.documentElement.lang = HTML_LANG[lang];
        this.apply();
        document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
    },

    apply() {
        document.querySelectorAll("[data-i18n]").forEach(el => {
            if (el.dataset.i18nSkip !== undefined) return; // elemento "ocupado" (ex: música tocando)
            el.textContent = this.t(el.dataset.i18n);
        });
        document.querySelectorAll("[data-i18n-aria]").forEach(el => {
            el.setAttribute("aria-label", this.t(el.dataset.i18nAria));
        });
        document.querySelectorAll("[data-lang-opt]").forEach(el => {
            const on = el.dataset.langOpt === this.lang;
            el.classList.toggle("active", on);
            el.setAttribute("aria-pressed", String(on));
        });
        // Link do WhatsApp já sai com a mensagem no idioma certo 💬
        const msg = encodeURIComponent(this.t("wa.msg"));
        document.querySelectorAll("[data-wa]").forEach(a => {
            a.href = `https://wa.me/5532998825125?text=${msg}`;
        });
    }
};

window.i18n = i18n;
document.addEventListener("DOMContentLoaded", () => i18n.setLang(i18n.lang));
